function applyTextureTrainerReviewOverrides(question) {
  const level = TT_REVIEW_LEVEL_OVERRIDES[question.id];
  const override = TT_REVIEW_QUESTION_OVERRIDES[question.id] || {};
  const updatedQuestion = {
    ...question,
    ...(level ? { level } : {}),
    ...override
  };

  if (override.markPoints) {
    updatedQuestion.acceptedAnswers = flattenPoints(override.markPoints, "acceptedAnswers");
    updatedQuestion.partialAnswers = flattenPoints(override.markPoints, "partialAnswers");
  }

  if (override.maxMarks) {
    updatedQuestion.maxMarks = override.maxMarks;
  }

  if (override.answerOptions) {
    updatedQuestion.answerChoices = override.answerOptions.slice();
  }

  return updatedQuestion;
}

