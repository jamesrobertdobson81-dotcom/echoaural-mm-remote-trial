  if (/HETEROPHON/.test(text)) support.push("related versions", "shared melodic framework", "same melodic material", "individual ornamentation", "small rhythmic or melodic differences");
  if (/ANTIPHONAL/.test(text)) support.push("answer one another", "contrast with one another", "between separated groups", "call and response");
