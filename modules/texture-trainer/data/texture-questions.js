function point(label, acceptedAnswers, partialAnswers = []) {
  return { label, acceptedAnswers, partialAnswers };
}

function flattenPoints(markPoints, field) {
  return markPoints.flatMap((markPoint) => markPoint[field] || []);
}

function createQuestion(config, markPoints) {
  return {
    id: config.id,
    module: "Texture Trainer",
    title: config.title,
    audio: config.audio,
    prompt: config.prompt,
    maxMarks: config.maxMarks,
    level: config.level || "",
    answerOptions: Array.isArray(config.answerOptions) ? config.answerOptions : [],
    answerChoices: Array.isArray(config.answerChoices) ? config.answerChoices : [],
    correctChoice: config.correctChoice || "",
    acceptedWrittenAnswers: Array.isArray(config.acceptedWrittenAnswers) ? config.acceptedWrittenAnswers : [],
    preferredAnswer: config.preferredAnswer || "",
    requiredConcepts: Array.isArray(config.requiredConcepts) ? config.requiredConcepts : [],
    optionalConcepts: Array.isArray(config.optionalConcepts) ? config.optionalConcepts : [],
    explanation: config.explanation || "",
    broadTextureCategory: config.broadTextureCategory || "",
    specificTextureTerm: config.specificTextureTerm || "",
    questionType: config.questionType || "",
    responseType: config.responseType || "",
    acceptedAnswers: flattenPoints(markPoints, "acceptedAnswers"),
    partialAnswers: flattenPoints(markPoints, "partialAnswers"),
    incorrectAnswers: config.incorrectAnswers || COMMON_TEXTURE_WRONG,
    markPoints,
    modelAnswer: config.modelAnswer,
    feedbackCorrect: config.feedbackCorrect,
    feedbackPartial: config.feedbackPartial,
    feedbackIncorrect: config.feedbackIncorrect,
    vocabularyTip: config.vocabularyTip,
    sourceModule: config.sourceModule || "",
    sourceClipId: config.sourceClipId || "",
    sourceAudioPath: config.sourceAudioPath || "",
    textureFocus: config.textureFocus || config.target || "",
    clipType: config.clipType || config.type || "",
    source: config.source || config.collection || "",
    rights: config.rights || config.licence || "",
    licenceStatus: config.licenceStatus || "",
    originalId: config.originalId || "",
    marksType: config.type || "",
    target: config.target || "",
    work: config.work || "",
    performer: config.performer || "",
    collection: config.collection || "",
    sourceUrl: config.sourceUrl || "",
    streamUrl: config.streamUrl || "",
    licence: config.licence || "",
    credit: config.credit || "",
    confidence: config.confidence || "",
    rationale: config.rationale || "",
    clipStart: Number(config.clipStart || 0),
    clipEnd: Number(config.clipEnd || config.audioDurationSeconds || 0),
    clipDuration: Number(config.audioDurationSeconds || 0),
    audioDurationSeconds: Number(config.audioDurationSeconds || 0)
  };
}

